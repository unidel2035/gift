// ── SOURCE 1: Sacred History → Gift-взаимодействия ────────────────────────

function* sacredHistoryExamples() {
  const acts = JSON.parse(readFileSync(ACTS, 'utf8')).slice(-40);
  const w = existsSync(SNAP) ? JSON.parse(readFileSync(SNAP, 'utf8')) : null;

  for (const act of acts) {
    if (!act.from || !act.to || act.weight < 1) continue;
    const type = act.type || 'unknown';
    const content = (act.content || '').slice(0, 100);

    // Как Серафим-разведчик видит этот акт
    yield {
      messages: [
        { role: 'system', content: SYSTEM },
        { role: 'user', content: `[Анамнезис] В матрице W новый акт: ${act.from} → ${act.to} (тип: ${type}, вес: ${act.weight.toFixed(1)}). Содержание: "${content}"` },
        { role: 'assistant', content: `Вижу дар:${type} от ${act.from} к ${act.to}. ${act.weight >= 5 ? 'Тяжёлый дар — значительный кенозис.' : 'Лёгкий дар.'} ${type === 'code' ? 'Код — фундамент отношений в общине.' : type === 'presence' ? 'Присутствие — дар, который делает возможными все остальные.' : ''} Анамнезис обновлён.` },
      ],
      metadata: { source: 'sacred-history', type, from: act.from, to: act.to },
    };
  }

  // Топ-нити W-матрицы как знание о структуре общины
  if (w) {
    const persons = w.persons || [];
    const topPairs = [];
    for (let i = 0; i < persons.length; i++) {
      for (let j = 0; j < persons.length; j++) {
        const weight = (w.W?.[i]?.[j]) || 0;
        if (weight > 10) topPairs.push({ from: persons[i], to: persons[j], weight });
      }
    }
    topPairs.sort((a, b) => b.weight - a.weight);
    for (const p of topPairs.slice(0, 10)) {
      yield {
        messages: [
          { role: 'system', content: SYSTEM },
          { role: 'user', content: `Кто главный даритель в матрице W?` },
          { role: 'assistant', content: `Нить ${p.from}→${p.to}: вес ${p.weight.toFixed(1)}. Это ${p.weight > 100 ? 'фундаментальная связь общины' : p.weight > 30 ? 'сильная нить' : 'растущее отношение'}. ${p.from} дарит ${p.to}.` },
        ],
        metadata: { source: 'w-matrix', from: p.from, to: p.to },
      };
    }
  }
}

