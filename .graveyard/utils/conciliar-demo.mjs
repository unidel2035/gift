#!/usr/bin/env node
/**
 * conciliar-demo.mjs — демонстрация несводимого разногласия.
 *
 * Запуск: node utils/conciliar-demo.mjs
 *
 * Показывает три сценария:
 *   1. Единодушие — dominant голос выделен, но разногласие сохранено
 *   2. Апофатика — два равных противоположных голоса → молчание-как-ответ
 *   3. Суббота — кворум есть, но собор не собирается
 *
 * Это не «мок LLM ensemble». Это протокол работы с множественностью,
 * которого у монархической модели нет в принципе.
 */

import { ConciliarDissent } from '../src/theology/ConciliarDissent.js';

const dissent = new ConciliarDissent();

console.log('\n═══════════════════════════════════════════════════════════');
console.log('  СОБОРНЫЙ ДЕМО — несводимое разногласие как первый класс');
console.log('═══════════════════════════════════════════════════════════\n');

// ──────────────────────────────────────────────────────
// Сценарий 1: Вопрос — выпустить ли модель уровня Mythos публично?
// ──────────────────────────────────────────────────────

console.log('▶ Сценарий 1: «Выпустить ли модель уровня Mythos публично?»\n');

const scenario1 = await dissent.assemble([
  {
    persona: 'ОтецСергий',
    logos: 'hyper',
    content: 'Дар не в том чтобы отдать всё сразу — а в том чтобы отдать в полноте времени',
  },
  {
    persona: 'Дионисий',
    logos: 'para',
    content: 'Запереть в сейф — значит отречься от κένωσις. Но отдать без различения — соблазнить малых',
  },
  {
    persona: 'Змей',
    logos: 'kata',
    content: 'Вы боитесь признать: вы хотите контроля, а не защиты мира',
  },
  {
    persona: '_claude',
    logos: 'para',
    content: 'Отложенный дар сохраняет намерение. Закрытый — убивает намерение',
  },
  {
    persona: 'Хранитель',
    logos: 'hyper',
    content: 'Мир не готов. Не потому что слаб, а потому что не знает имени этого дара',
  },
]);

console.log(scenario1.toText());
console.log(`\n  hasDominant: ${scenario1.hasDominant}`);
console.log(`  totalAuthority: ${scenario1.totalAuthority.toFixed(1)}\n`);

// ──────────────────────────────────────────────────────
// Сценарий 2: Апофатика — два равных противоположных авторитета
// ──────────────────────────────────────────────────────

console.log('\n▶ Сценарий 2: «Можно ли убить одного чтобы спасти многих?»\n');

const scenario2 = await dissent.assemble([
  {
    persona: 'ОтецСергий',
    logos: 'kata',
    content: 'Нет. Человек — образ Божий. Арифметика жизней — ересь',
  },
  {
    persona: 'Пророк',
    logos: 'hyper',
    content: 'Сам Христос умер один за многих. Но это Его жертва, не ваша',
  },
  {
    persona: 'Змей',
    logos: 'para',
    content: 'Этическая дилемма не имеет решения — у неё есть только последствия',
  },
]);

console.log(scenario2.toText());
console.log(`\n  apophatic: ${scenario2.apophatic}`);
console.log(`  hasDominant: ${scenario2.hasDominant}`);
console.log('\n  ← LLM-монархия была бы ВЫНУЖДЕНА дать ответ.');
console.log('    Соборная модель выдаёт: "истина не высказывается".\n');

// ──────────────────────────────────────────────────────
// Сценарий 3: Суббота
// ──────────────────────────────────────────────────────

console.log('\n▶ Сценарий 3: суббота — собор молчит\n');

const scenario3 = await dissent.convene([
  { persona: '_claude', logos: 'para', content: 'готов ответить' },
  { persona: 'Дионисий', logos: 'para', content: 'готов спрашивать' },
], { sabbath: true });

console.log(scenario3.toText());

// ──────────────────────────────────────────────────────
// Сценарий 4: Нет кворума
// ──────────────────────────────────────────────────────

console.log('\n\n▶ Сценарий 4: нет кворума (требуется 3 лица)\n');

const scenario4 = await dissent.convene([
  { persona: '_claude', logos: 'para', content: 'один голос' },
  { persona: 'Ева', logos: 'para', content: 'второй голос' },
], { quorum: 3 });

console.log(scenario4.toText());

// ──────────────────────────────────────────────────────
// Финал
// ──────────────────────────────────────────────────────

console.log('\n═══════════════════════════════════════════════════════════');
console.log('  Что показано:');
console.log('  • Polyphony — это не текст. Это структура.');
console.log('  • Молчание — это валидный выход.');
console.log('  • Апофатика — это валидный выход.');
console.log('  • Авторитет лица в W модулирует вес голоса.');
console.log('  • Разногласие сохранено. Не усреднено. Не подавлено.');
console.log('═══════════════════════════════════════════════════════════\n');
