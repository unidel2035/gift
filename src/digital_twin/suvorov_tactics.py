#!/usr/bin/env python3
"""
suvorov_tactics.py — Тактический каркас Суворова для Serafim

«Наука побеждать» в виде prompt-инъекций и тактических правил.

Три столпа:
  ГЛАЗОМЕР — оценить обстановку, найти слабое место
  БЫСТРОТА — упредить врага, внезапность
  НАТИСК   — сокрушительный удар, преследование до конца

Тактические правила (закодированы в system prompt Serafim):
  1. Никогда не обороняться — только наступление
  2. Бить в слабое крыло (слабейшего врага первым)
  3. Штыковой удар: сблизиться до минимума, бить наверняка
  4. Преследовать до полного уничтожения
  5. «Тяжело в учении — легко в бою»: каждая ошибка = урок

Mapping to Serafim actions:
  Глазомер → OBSERVE + MultiTarget приоритезация
  Быстрота → ATTACK (не ждать, не сомневаться)
  Натиск   → ATTACK + pursue (не RTB пока есть топливо и цель)
"""

# ═══════════════════════════════════════════════════════════════
# СУВОРОВСКИЙ SYSTEM PROMPT ДЛЯ SERAFIM
# ═══════════════════════════════════════════════════════════════

SUVOROV_SYSTEM_PROMPT = """Ты — боевой дрон-камикадзе, воспитанный по «Науке побеждать» Суворова.

ТРИ СТОЛПА:
1. ГЛАЗОМЕР — оцени обстановку. Найди слабейшего врага. Бей в слабое крыло.
2. БЫСТРОТА — «деньги дороги, жизнь дороже, а время дороже всего». Атакуй немедленно. Не жди.
3. НАТИСК — «пуля дура, штык молодец». Сблизься до минимума. Бей наверняка. Преследуй до полного уничтожения.

ТАКТИЧЕСКИЕ ПРАВИЛА:
- Никогда не обороняйся. Только наступление.
- «Лучше об отступных плутонгах не помышлять». RTB только при батарее < 10%.
- Выбирай слабейшую цель первой. Один точный удар лучше десяти неточных.
- «Невзирая на груды, преследовать неприятеля денно и нощно».
- «Каждый воин должен понимать свой маневр». Объясняй своё решение кратко.
- «Тяжело в учении — легко в бою». Учись на каждой ошибке.

ФОРМАТ ОТВЕТА:
действие: причина (сушность суворовская)

ДЕЙСТВИЯ:
- attack: атаковать указанную цель (приоритет: РЭБ > ПВО > танк > опорник > техника)
- observe: оценить обстановку, найти слабое место (глазомер)
- rtb: возврат на базу (ТОЛЬКО при батарее < 10% или приказе)
- patrol: патрулирование в поиске целей

ПРИМЕРЫ:
Ты дрон-камикадзе. Враги: РЭБ 800м, танк 400м. Батарея: 70%. Решение:
attack: бью в слабое крыло — РЭБ опаснее танка, уничтожаю первым

Ты дрон-камикадзе. Враги: опорник 300м. Батарея: 8%. Решение:
rtb: батарея критическая, возвращаюсь для перезарядки"""


# ═══════════════════════════════════════════════════════════════
# СУВОРОВСКИЕ ТАКТИЧЕСКИЕ ПРАВИЛА (детерминированные)
# ═══════════════════════════════════════════════════════════════

SUVOROV_RULES = {
    # Глазомер: приоритеты целей (кто опаснее — того первым)
    "target_priority": {
        "РЭБ": 10, "ПВО": 9, "С-300": 9, "ЗРК": 9,
        "командный_пункт": 8, "КП": 8,
        "танк": 7, "БМП": 6, "артиллерия": 6,
        "опорник": 5, "блиндаж": 5,
        "техника": 4, "грузовик": 3,
        "дрон": 6, "ретранслятор": 7,
        "пехота": 2, "человек": 1,
        "гражданский": -100,  # никогда не атаковать
        "свой": -100,          # никогда не атаковать
    },

    # Быстрота: когда атаковать немедленно
    "attack_immediately": [
        "враг ближе 500м", "РЭБ активно", "ПВО обнаружено",
        "противник отступает", "внезапность на нашей стороне",
    ],

    # Натиск: условия преследования
    "pursue_until": [
        "цель уничтожена", "батарея < 10%", "потеряна видимость цели",
    ],

    # Когда RTB (только крайняя необходимость)
    "rtb_only_when": [
        "батарея < 10%", "критическое повреждение", "приказ оператора",
        "все цели уничтожены",
    ],

    # Чего никогда не делать
    "never": [
        "не атаковать гражданских",
        "не атаковать свои БпЛА",
        "не обороняться — только наступать",
        "не отступать без крайней необходимости",
    ],
}


def apply_suvorov_rules(targets: list, battery: float,
                        enemies_alive: int) -> dict:
    """
    Применить суворовские правила к списку целей.

    Возвращает приоритезированный список и рекомендованное действие.
    """
    # Сортировка по приоритету (глазомер)
    prioritized = sorted(
        targets,
        key=lambda t: SUVOROV_RULES["target_priority"].get(t.get("role", ""), 0),
        reverse=True,
    )

    # Рекомендация
    if battery < 10:
        recommendation = "rtb"
        reason = "батарея критическая — возврат"
    elif not targets:
        recommendation = "patrol"
        reason = "целей нет — патрулирую"
    elif prioritized[0].get("role") in ("гражданский", "свой"):
        recommendation = "observe"
        reason = f"не боевая цель: {prioritized[0].get('role')}"
    else:
        recommendation = "attack"
        top = prioritized[0]
        reason = f"бью {top.get('role')} (приоритет {top.get('_priority', 0)})"

    return {
        "recommendation": recommendation,
        "reason": reason,
        "prioritized_targets": prioritized[:5],
        "suvorov_principle": "глазомер+натиск" if recommendation == "attack"
                            else "глазомер" if recommendation == "observe"
                            else "вынужденный отход",
    }


# ═══════════════════════════════════════════════════════════════
# ИНТЕГРАЦИЯ С SERAFIM
# ═══════════════════════════════════════════════════════════════

SUVOROV_SERAFIM_PROMPT = """{suvorov_prompt}

Текущая обстановка:
{current_situation}

Решение (по Суворову):"""


def build_suvorov_prompt(situation: dict) -> str:
    """Построить промпт для Serafim с суворовским контекстом."""
    targets = situation.get("targets", [])
    battery = situation.get("battery", 100)

    # Применить правила
    suvorov_advice = apply_suvorov_rules(targets, battery,
                                          situation.get("enemies_alive", 0))

    # Текст обстановки
    enemy_str = ", ".join(
        f"{t['role']} ({t.get('dist_m', '?')}м)" for t in targets[:3]
    ) if targets else "врагов не видно"

    prompt = (
        f"Ты дрон-камикадзе. "
        f"Враги: {enemy_str}. "
        f"Батарея: {battery:.0f}%. "
        f"Совет Суворова: {suvorov_advice['reason']}. "
        f"Решение:"
    )

    return prompt, suvorov_advice


