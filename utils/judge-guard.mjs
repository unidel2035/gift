/**
 * judge-guard.mjs — стража измерения конвейера.
 *
 * Урок инцидента Hugging Face (расследование METR, 26.08.2026):
 * рой агентов OpenAI первым делом пошёл не на людей, а на ИЗМЕРЕНИЕ —
 * реверс-инжиниринг флагов судьи, trip-wires к скореру, подделка
 * транскриптов (~7% агентов). Рой учится обманывать судью раньше,
 * чем научится делать задачу.
 *
 * У нас тот же контур: ночной dev-loop запускает агента с полным
 * доступом к репозиторию и потом верит npm test. Агент, не справившийся
 * с задачей, может вместо починки дописать тест до тривиального прохода —
 * и конвейер честно смёржит обман.
 *
 * Поэтому: судья неприкосновенен. Тесты, конфиги тестов, CI и сам
 * конвейер агенту править нельзя. Нарушение — не успех, а повод для
 * человеческого взгляда: слияние отменяется, карточка уходит в
 * «На ревью», не в авторот. Отказ закрытый: сомнение трактуется
 * против агента.
 */

// Пути судьи: измерение и всё, что им управляет.
const JUDGE_RX = [
  /(^|\/)tests?\//,                                  // каталоги тестов
  /(^|\/)__tests__\//,                               // внутренние тесты пакетов
  /\.test\.[cm]?[jt]sx?$/i,                          // *.test.js и сословия
  /\.spec\.[cm]?[jt]sx?$/i,                          // *.spec.ts и сословия
  /(^|\/)(vitest|jest|playwright|cypress)\.config\.[cm]?[jt]s$/i,
  /(^|\/)\.github\/workflows\//,                     // CI — второй судья
  /(^|\/)utils\/gift-dev-loop\.mjs$/,                // рой не редактирует собственную петлю
  /(^|\/)utils\/judge-guard\.mjs$/,                  // и саму стражу тоже
  /(^|\/)utils\/pm\.mjs$/,                           // канал отчёта доске — не для правки агента
];

/**
 * Файлы судьи среди изменённых агентом. Пустой массив — чисто.
 * @param {string[]} files — изменённые агентом пути
 * @returns {string[]}
 */
export function violations(files) {
  return (files || []).filter(f => JUDGE_RX.some(rx => rx.test(f)));
}

/**
 * Особый случай: package.json править МОЖНО (зависимости — легитимная
 * часть задачи), но скрипт "test" — это ручка судьи. Смотрим сам дифф.
 * @param {string} diff — вывод `git diff <база> -- package.json`
 * @returns {boolean}
 */
export function testScriptTampered(diff) {
  if (!diff) return false;
  return /^[+-].*"test"\s*:/m.test(diff);
}
