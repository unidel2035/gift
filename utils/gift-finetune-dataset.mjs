// ── CLI ──────────────────────────────────────────────────────────────────────

const MODE = process.argv[2] || 'serafim';

let examples;
if (MODE === 'serafim') {
  examples = generateSerafim();
} else if (MODE === 'social') {
  examples = generateSocialDilemmas();
} else if (MODE === 'domain') {
  examples = generateDomainTerms();
} else if (MODE === 'all') {
  examples = [...generateSerafim(), ...generateSocialDilemmas(), ...generateDomainTerms()];
} else {
  console.error('gift-finetune-dataset: serafim | social | domain | all');
  process.exit(1);
}

for (const ex of examples) {
  console.log(JSON.stringify(ex));
}

console.error(`  ✓ ${MODE}: ${examples.length} примеров`);
