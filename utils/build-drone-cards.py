# ── Стили ────────────────────────────────────────────────────────────────────

def fill(hex_color):
    return PatternFill("solid", fgColor=hex_color)

def thin_border():
    s = Side(style="thin", color="BDBDBD")
    return Border(left=s, right=s, top=s, bottom=s)

def left(wrap=True):
    return Alignment(horizontal="left", vertical="top", wrap_text=wrap)

def center(wrap=False):
    return Alignment(horizontal="center", vertical="top", wrap_text=wrap)

def hfont(color=HEADER_FG, size=10, bold=True):
    return Font(name="Calibri", bold=bold, size=size, color=color)

def bfont(color="1A1A1A", size=10, bold=False):
    return Font(name="Calibri", size=size, color=color, bold=bold)

