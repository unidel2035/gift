#!/usr/bin/env node
/**
 * gift-sovereignty.mjs — Модульный суверенитет из W-матрицы
 *
 * Паттерн: Polycentric Governance (Ostrom), Хозрасчёт (советская кибернетика),
 * Cybersyn-субсидиарность.
 *
 * Кто имеет вес в модуле — тот и sovereign. Не назначенный CODEOWNERS,
 * а эмерджентный из даров кода.
 *
 * Генерирует:
 *   1. CODEOWNERS на основе W-матрицы (кто сколько дал в файлы модуля)
 *   2. Карту суверенитета: module → { sovereign, weight, contributors }
 *   3. Рекомендации: кому доверить ревью, кого спросить
 *
 * Использование:
 *   node utils/gift-sovereignty.mjs generate
 *   node utils/gift-sovereignty.mjs map
 *   node utils/gift-sovereignty.mjs recommend --file src/core/auth.ts
 */

import { readFileSync, writeFileSync, existsSync } from 'fs';
import { resolve, dirname, relative } from 'path';
import { fileURLToPath } from 'url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SNAP = resolve(ROOT, 'data/sacred-history-W.json');
const ACT_INDEX = resolve(ROOT, 'data/act-index.json');
const SOVEREIGNTY_FILE = resolve(ROOT, '.giftsovereignty.json');

// ── Module classification ────────────────────────────────────────────────────

function moduleForFile(filePath) {
  const rel = relative(ROOT, filePath);
  const parts = rel.split('/');
  if (parts[0] === 'src') return `src/${parts[1] || ''}`;
  if (parts[0] === 'specs') return 'specs';
  if (parts[0] === 'utils') return 'utils';
  if (parts[0] === 'bin') return 'bin';
  if (parts[0] === 'data') return 'data';
  return 'root';
}

// ── W-matrix based sovereignty ───────────────────────────────────────────────

export function computeSovereignty() {
  const modules = {};

  try {
    if (!existsSync(ACT_INDEX)) return modules;

    const acts = JSON.parse(readFileSync(ACT_INDEX, 'utf8'));

    for (const act of acts) {
      if (act.type !== 'code') continue;

      // Try to infer module from content (file paths mentioned)
      const content = act.content || '';
      const fileMatch = content.match(/src\/[^\s,;]+/g) || [];
      const modulesTouched = new Set(fileMatch.map(moduleForFile));

      // If no file match, infer from linked issue or commit context
      if (modulesTouched.size === 0) {
        // fallback: count as root contribution
        modulesTouched.add('root');
      }

      for (const mod of modulesTouched) {
        if (!modules[mod]) modules[mod] = { contributors: {} };
        if (!modules[mod].contributors[act.from]) {
          modules[mod].contributors[act.from] = { weight: 0, acts: 0 };
        }
        modules[mod].contributors[act.from].weight += act.weight || 1;
        modules[mod].contributors[act.from].acts += 1;
      }
    }
  } catch {}

  // Compute sovereign (highest weight contributor) per module
  for (const [mod, data] of Object.entries(modules)) {
    let maxWeight = 0;
    let sovereign = null;
    for (const [agent, contrib] of Object.entries(data.contributors)) {
      if (contrib.weight > maxWeight) {
        maxWeight = contrib.weight;
        sovereign = agent;
      }
    }
    data.sovereign = sovereign;
    data.totalWeight = maxWeight;
    data.contributorsList = Object.entries(data.contributors)
      .map(([agent, c]) => ({ agent, ...c }))
      .sort((a, b) => b.weight - a.weight);
  }

  return modules;
}

// ── CODEOWNERS generation ────────────────────────────────────────────────────

export function generateCodeowners() {
  const sovereignty = computeSovereignty();
  const lines = ['# Auto-generated by gift-sovereignty.mjs from W-matrix', '#'];

  for (const [mod, data] of Object.entries(sovereignty)) {
    if (!data.sovereign) continue;
    const top3 = data.contributorsList.slice(0, 3).map(c => `@${c.agent}`).join(' ');
    lines.push('');
    lines.push(`# ${mod} — sovereign: ${data.sovereign} (weight: ${data.totalWeight.toFixed(1)})`);
    if (mod === 'root') {
      lines.push(`* ${top3}`);
    } else {
      lines.push(`/${mod}/ ${top3}`);
    }
  }

  return lines.join('\n');
}

// ── Recommend reviewer ──────────────────────────────────────────────────────

export function recommendReviewer(filePath) {
  const sovereignty = computeSovereignty();
  const mod = moduleForFile(filePath);

  if (sovereignty[mod]) {
    return {
      file: filePath,
      module: mod,
      sovereign: sovereignty[mod].sovereign,
      topReviewers: sovereignty[mod].contributorsList.slice(0, 3),
    };
  }

  // Fallback: find closest module
  const parts = mod.split('/');
  for (let i = parts.length - 1; i >= 0; i--) {
    const parent = parts.slice(0, i + 1).join('/');
    if (sovereignty[parent]) {
      return {
        file: filePath,
        module: parent,
        sovereign: sovereignty[parent].sovereign,
        topReviewers: sovereignty[parent].contributorsList.slice(0, 3),
      };
    }
  }

  return { file: filePath, module: 'unknown', sovereign: null, topReviewers: [] };
}

// ── Persist ──────────────────────────────────────────────────────────────────

export function saveSovereignty() {
  const sovereignty = computeSovereignty();
  writeFileSync(SOVEREIGNTY_FILE, JSON.stringify(sovereignty, null, 2));
  return sovereignty;
}

// ── CLI ──────────────────────────────────────────────────────────────────────

const CMD = process.argv[2];

if (CMD === 'generate') {
  const codeowners = generateCodeowners();
  console.log(codeowners);
  const outFile = resolve(ROOT, 'CODEOWNERS');
  writeFileSync(outFile, codeowners + '\n');
  console.log(`\n  ✓ CODEOWNERS записан (${Object.keys(computeSovereignty()).length} модулей)`);
} else if (CMD === 'map') {
  const sov = computeSovereignty();
  console.log(JSON.stringify(sov, null, 2));
} else if (CMD === 'recommend') {
  const file = process.argv.find((_, i) => process.argv[i-1] === '--file');
  if (!file) { console.error('recommend --file <path>'); process.exit(1); }
  const rec = recommendReviewer(file);
  console.log(JSON.stringify(rec, null, 2));
  if (rec.sovereign) {
    console.log(`\n  👑 Суверен ${rec.module}: ${rec.sovereign}`);
    console.log(`  Рецензенты: ${rec.topReviewers.map(r => `${r.agent}(${r.weight.toFixed(1)})`).join(', ')}`);
  }
} else if (CMD === 'save') {
  const sov = saveSovereignty();
  console.log(`  ✓ Суверенитет сохранён: ${Object.keys(sov).length} модулей`);
  for (const [mod, data] of Object.entries(sov)) {
    console.log(`    ${mod}: ${data.sovereign} (${data.totalWeight.toFixed(1)})`);
  }
} else {
  console.error('gift-sovereignty: generate | map | recommend --file <path> | save');
  process.exit(1);
}
